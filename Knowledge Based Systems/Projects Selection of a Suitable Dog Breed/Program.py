import csv

def load_dogs_from_csv(path: str = "dogs.csv"):
    dogs = []
    with open(path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            dog = {
                "breed": row["breed"],
                "housing_size": row["housing_size"],
                "prefers_small": row["prefers_small"].strip() == "True",
                "coat_care_ready": row["coat_care_ready"].strip() == "True",
                "activity_important": row["activity_important"].strip() == "True",
                "dog_friendly": row["dog_friendly"].strip() == "True",
                "good_with_children": row["good_with_children"].strip() == "True",
                "bark_important": row["bark_important"].strip() == "True",
                "trainability": row["trainability"].strip() == "True",
                "outdoor_time": row["outdoor_time"].strip() == "True",
            }
            dogs.append(dog)
    return dogs

dogs = load_dogs_from_csv("dogs.csv")

def create_rules_from_dogs(dogs_list):
    rules = []
    for dog in dogs_list:
        conditions = []
        for field, value in dog.items():
            if field == "breed":
                continue
            conditions.append((field, value))
        rule = {
            "hypothesis": f"Plemeno {dog['breed']} je vhodné pre používateľa",
            "breed": dog["breed"],
            "conditions": conditions
        }
        rules.append(rule)
    return rules


rules = create_rules_from_dogs(dogs)

